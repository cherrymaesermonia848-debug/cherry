create table if not exists public.festival (
  id bigint generated by default as identity primary key,
  name text not null,
  image_url text,
  image_path text,
  short_description text not null default '',
  details text not null default '',
  status text not null default 'draft' check (status in ('published', 'draft')),
  featured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint festival_featured_must_be_published check (not featured or status = 'published')
);

create or replace function public.enforce_festival_featured_and_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();

  if new.featured then
    if new.status <> 'published' then
      raise exception 'Only published festivals can be featured'
        using errcode = '23514';
    end if;

    update public.festival
    set featured = false,
        updated_at = now()
    where featured = true
      and id is distinct from new.id;
  end if;

  return new;
end;
$$;

drop trigger if exists festival_enforce_featured_and_updated_at on public.festival;
create trigger festival_enforce_featured_and_updated_at
before insert or update on public.festival
for each row execute function public.enforce_festival_featured_and_updated_at();

create unique index if not exists festival_only_one_featured_idx
  on public.festival ((featured))
  where featured = true;

alter table public.festival enable row level security;

drop policy if exists festival_public_read_published on public.festival;
create policy festival_public_read_published
  on public.festival
  for select
  to anon, authenticated
  using (status = 'published');

